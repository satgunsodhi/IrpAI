"""
Context Pack Schema

Defines the structured output format that IrpAI produces.  This is
the "context pack" that gets attached to an LLM prompt.

The schema is designed to be:
    - Token-efficient (compact JSON, no redundancy)
    - Semantically clear (LLMs can parse it without explanation)
    - Hierarchical (mirrors the visual layout of the screen)
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from typing import Any, Literal


@dataclass
class Region:
    """A single screen region in the context pack."""

    role: str
    """Semantic role: 'heading', 'body', 'button', 'nav', 'icon', …"""

    text: str = ""
    """Extracted text content."""

    bbox: tuple[int, int, int, int] | None = None
    """Bounding box [x1, y1, x2, y2] in pixels (optional)."""

    confidence: float = 1.0
    """Model confidence score (optional)."""

    children: list[Region] = field(default_factory=list)
    """Nested sub-regions."""

    properties: dict[str, Any] = field(default_factory=dict)
    """Extra properties (font_size, element_type, …)."""


@dataclass
class ScreenSummary:
    """
    Natural-language summary of the screenshot, generated by
    combining OCR text and detection labels.
    """

    description: str = ""
    """One-paragraph summary of what's on screen."""

    app_type: str = ""
    """Detected application type: 'browser', 'ide', 'terminal', 'chat', …"""

    key_elements: list[str] = field(default_factory=list)
    """Bullet list of the most important elements / actions visible."""




@dataclass
class PipelineMetadata:
    """Metadata about the pipeline run that produced this context pack."""

    irpai_version: str = ""
    tier: str = ""
    ocr_engine: str = ""
    detection_model: str = ""
    total_ms: float = 0.0
    image_size: tuple[int, int] = (0, 0)


@dataclass
class ContextPack:
    """
    The complete structured context output of IrpAI.

    This is the object that gets serialised and injected into an
    LLM prompt to give it understanding of a screenshot.

    Example JSON output::

        {
          "summary": {
            "description": "A VS Code editor showing a Python file ...",
            "app_type": "ide",
            "key_elements": ["editor tab", "file tree", "terminal"]
          },
          "regions": [
            {"role": "heading", "text": "test.py", "bbox": [10, 5, 200, 30]},
            {"role": "body", "text": "def main(): ...", "bbox": [10, 35, 800, 400]},
            ...
          ],
          "hierarchy": { ... },
                    "meta": { "tier": "standard", "ocr_engine": "easyocr", ... }
        }
    """

    summary: ScreenSummary = field(default_factory=ScreenSummary)
    regions: list[Region] = field(default_factory=list)
    hierarchy: dict[str, Any] = field(default_factory=dict)
    meta: PipelineMetadata = field(default_factory=PipelineMetadata)

    # -- serialisation ------------------------------------------------------

    def to_dict(
        self,
        *,
        include_bboxes: bool = True,
        include_confidence: bool = True,
        include_hierarchy: bool = True,
        include_meta: bool = True,
    ) -> dict[str, Any]:
        """Convert to a plain dict suitable for JSON serialisation."""
        d: dict[str, Any] = {
            "summary": _summary_dict(self.summary),
        }

        d["regions"] = [
            _region_dict(r, include_bboxes=include_bboxes, include_confidence=include_confidence)
            for r in self.regions
        ]

        if include_hierarchy and self.hierarchy:
            d["hierarchy"] = self.hierarchy

        if include_meta:
            d["meta"] = asdict(self.meta)

        return d

    def to_json(self, *, compact: bool = True, **kwargs: Any) -> str:
        """Serialise to a JSON string."""
        d = self.to_dict(**kwargs)
        if compact:
            return json.dumps(d, separators=(",", ":"), ensure_ascii=False)
        return json.dumps(d, indent=2, ensure_ascii=False)

    def to_markdown(self) -> str:
        """
        Serialise to a Markdown string optimised for LLM consumption.

        This is an alternative to JSON that some LLMs handle better.
        """
        parts: list[str] = []

        # Summary
        parts.append("## Screenshot Context")
        if self.summary.description:
            parts.append(self.summary.description)
        if self.summary.app_type:
            parts.append(f"**App type:** {self.summary.app_type}")
        if self.summary.key_elements:
            parts.append("**Key elements:** " + ", ".join(self.summary.key_elements))
        parts.append("")

        # Regions
        parts.append("## Screen Regions")
        for r in self.regions:
            prefix = f"[{r.role.upper()}]"
            if r.text:
                parts.append(f"- {prefix} {r.text[:200]}")
            else:
                parts.append(f"- {prefix} (no text)")
        parts.append("")

        return "\n".join(parts)

    def token_estimate(self) -> int:
        """
        Rough token count estimate (1 token ≈ 4 chars for English).
        Useful for checking against :attr:`OutputConfig.max_context_tokens`.
        """
        text = self.to_json(compact=True)
        return len(text) // 4


# -- helpers ----------------------------------------------------------------

def _summary_dict(s: ScreenSummary) -> dict[str, Any]:
    d: dict[str, Any] = {}
    if s.description:
        d["description"] = s.description
    if s.app_type:
        d["app_type"] = s.app_type
    if s.key_elements:
        d["key_elements"] = s.key_elements
    return d


def _region_dict(
    r: Region,
    *,
    include_bboxes: bool = True,
    include_confidence: bool = True,
) -> dict[str, Any]:
    d: dict[str, Any] = {"role": r.role}
    if r.text:
        d["text"] = r.text
    if include_bboxes and r.bbox:
        d["bbox"] = list(r.bbox)
    if include_confidence and r.confidence < 1.0:
        d["confidence"] = round(r.confidence, 3)
    if r.properties:
        d["properties"] = r.properties
    if r.children:
        d["children"] = [
            _region_dict(c, include_bboxes=include_bboxes, include_confidence=include_confidence)
            for c in r.children
        ]
    return d
